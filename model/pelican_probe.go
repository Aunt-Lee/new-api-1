package model

import "time"

const (
	PelicanTestStatusSuccess = "success"
	PelicanTestStatusInvalid = "invalid"
)

// ProbeGroupInfo describes a group that currently has at least one enabled
// channel, together with its review state. The admin page uses this to build
// the selectable probe target list dynamically instead of a hardcoded list.
type ProbeGroupInfo struct {
	Group          string   `json:"group"`
	ChannelCount   int64    `json:"channel_count"`
	PublishedCount int64    `json:"published_count"`
	PendingCount   int64    `json:"pending_count"`
	// Models are the distinct enabled models available in this group. The admin
	// page uses them to offer model-level probe targets instead of a hardcoded
	// single model, while the group still decides which channel pool is used.
	Models []string `json:"models"`
}

// GetProbeGroups returns every group with at least one enabled channel plus a
// per-group count of published/pending probe results. Querying abilities keeps
// the list in sync with the actual channel configuration: adding a channel or
// enabling a new group immediately makes it selectable, no code change needed.
func GetProbeGroups() ([]ProbeGroupInfo, error) {
	var groups []ProbeGroupInfo
	if err := DB.Table("abilities").
		Where("enabled = ?", true).
		Select(commonGroupCol + ", COUNT(DISTINCT channel_id) AS channel_count").
		Group(commonGroupCol).
		Order(commonGroupCol).
		Scan(&groups).Error; err != nil {
		return nil, err
	}

	// Attach review stats. Legacy rows with NULL pending count as published,
	// matching GetLatestPelicanTests.
	type stat struct {
		Group          string
		PublishedCount int64
		PendingCount   int64
	}
	var stats []stat
	if err := DB.Model(&PelicanTest{}).
		Select(commonGroupCol+", "+
			"SUM(CASE WHEN pending = ? OR pending IS NULL THEN 1 ELSE 0 END) AS published_count, "+
			"SUM(CASE WHEN pending = ? THEN 1 ELSE 0 END) AS pending_count", false, true).
		Group(commonGroupCol).
		Scan(&stats).Error; err != nil {
		return nil, err
	}
	byGroup := make(map[string]stat, len(stats))
	for _, s := range stats {
		byGroup[s.Group] = s
	}

	// Attach the enabled models for each group. One query for all groups keeps
	// the admin page responsive even with many channels.
	type modelRow struct {
		Group string `gorm:"column:group_name"`
		Model string `gorm:"column:model"`
	}
	var modelRows []modelRow
	if err := DB.Table("abilities").
		Where("enabled = ?", true).
		Select(commonGroupCol + " AS group_name, model").
		Group(commonGroupCol + ", model").
		Order("model").
		Scan(&modelRows).Error; err != nil {
		return nil, err
	}
	modelsByGroup := make(map[string][]string, len(groups))
	for _, r := range modelRows {
		modelsByGroup[r.Group] = append(modelsByGroup[r.Group], r.Model)
	}

	for i := range groups {
		if s, ok := byGroup[groups[i].Group]; ok {
			groups[i].PublishedCount = s.PublishedCount
			groups[i].PendingCount = s.PendingCount
		}
		if m, ok := modelsByGroup[groups[i].Group]; ok {
			groups[i].Models = m
		} else {
			groups[i].Models = []string{}
		}
	}
	return groups, nil
}

// PelicanTest stores one animated "little crocodile riding a bicycle" SVG
// probe result for a group. The raw SVG is kept so the public page can show
// the untouched model output. The historical "pelican" name is deliberately
// kept for the existing table / endpoint / symbol names; only the subject
// changed (2026-11-09).
type PelicanTest struct {
	Id         int    `json:"id" gorm:"primaryKey"`
	Group      string `json:"group" gorm:"column:group;size:64;index:idx_pelican_group_created,priority:1"`
	ModelName  string `json:"model_name" gorm:"size:128"`
	Content    string `json:"content" gorm:"type:text"`
	Status     string `json:"status" gorm:"size:16"`
	FailReason string `json:"fail_reason" gorm:"size:255"`
	// Pending marks a result that was generated by a manual admin probe but has
	// not been reviewed/published yet. Only published rows (pending=false) are
	// exposed on the public pricing page. No default tag is used on purpose
	// (three-dialect compat): legacy rows added by AutoMigrate hold NULL and are
	// treated as published by the queries below, so existing public data keeps
	// showing without a data migration.
	Pending   bool  `json:"pending" gorm:"column:pending"`
	CreatedAt int64 `json:"created_at" gorm:"index:idx_pelican_group_created,priority:2"`
}

func (PelicanTest) TableName() string {
	return "pelican_tests"
}

// GetPelicanTestGroups returns every group that already has stored probe
// results. Used by the admin review list so results for a group whose channels
// were later disabled remain reviewable and publishable.
func GetPelicanTestGroups() ([]string, error) {
	var groups []string
	err := DB.Model(&PelicanTest{}).
		Distinct().
		Order(commonGroupCol).
		Pluck(commonGroupCol, &groups).Error
	return groups, err
}

func InsertPelicanTest(record *PelicanTest) error {
	if record == nil {
		return nil
	}
	if record.CreatedAt == 0 {
		record.CreatedAt = time.Now().Unix()
	}
	return DB.Create(record).Error
}

// GetLatestPelicanTests returns up to perGroup most recent PUBLISHED results
// for each requested group, newest first within that group. Pending rows are
// excluded so the public pricing page never shows unreviewed output. Legacy
// rows whose pending column is NULL are treated as published.
// Querying per group keeps the result set bounded (only the rows we actually
// render, including their SVG payloads, are loaded) and avoids dialect-specific
// window functions.
func GetLatestPelicanTests(groups []string, perGroup int) ([]PelicanTest, error) {
	return getPelicanTestsByPublishState(groups, perGroup, false)
}

// GetLatestPelicanTestsForAdmin returns recent results for each group including
// pending ones, for the admin review page.
func GetLatestPelicanTestsForAdmin(groups []string, perGroup int) ([]PelicanTest, error) {
	return getPelicanTestsByPublishState(groups, perGroup, true)
}

// publishedFilter selects published rows when includePending is false. NULL is
// accepted as published for smooth upgrade of historical rows.
func getPelicanTestsByPublishState(groups []string, perGroup int, includePending bool) ([]PelicanTest, error) {
	if perGroup <= 0 {
		perGroup = 4
	}
	result := make([]PelicanTest, 0, len(groups)*perGroup)
	for _, group := range groups {
		var rows []PelicanTest
		q := DB.Model(&PelicanTest{}).Where(commonGroupCol+" = ?", group)
		if !includePending {
			q = q.Where("pending = ? OR pending IS NULL", false)
		}
		err := q.
			Order("created_at DESC").
			Order("id DESC").
			Limit(perGroup).
			Find(&rows).Error
		if err != nil {
			return nil, err
		}
		result = append(result, rows...)
	}
	return result, nil
}

// GetPelicanTestByID fetches a single row by primary key.
func GetPelicanTestByID(id int) (*PelicanTest, error) {
	var row PelicanTest
	if err := DB.Where("id = ?", id).First(&row).Error; err != nil {
		return nil, err
	}
	return &row, nil
}

// PublishPelicanTest marks a pending result as published (pending=false) so it
// becomes visible on the public pricing page.
func PublishPelicanTest(id int) error {
	return DB.Model(&PelicanTest{}).Where("id = ?", id).Update("pending", false).Error
}

// DeletePelicanTest removes a result permanently (used to discard a pending
// probe that the admin does not want to publish).
func DeletePelicanTest(id int) error {
	return DB.Where("id = ?", id).Delete(&PelicanTest{}).Error
}

// GetLatestSuccessfulPelicanTestTime returns the timestamp of the most recent
// *successful* probe run across all groups. Failed runs are deliberately
// excluded: a failed run must not push the next attempt 12 hours away.
func GetLatestSuccessfulPelicanTestTime() (int64, error) {
	var latest int64
	err := DB.Model(&PelicanTest{}).
		Where("status = ?", PelicanTestStatusSuccess).
		Select("COALESCE(MAX(created_at), 0)").
		Scan(&latest).Error
	return latest, err
}

func DeletePelicanTestsBefore(cutoffTs int64) error {
	if cutoffTs <= 0 {
		return nil
	}
	return DB.Where("created_at < ?", cutoffTs).Delete(&PelicanTest{}).Error
}
